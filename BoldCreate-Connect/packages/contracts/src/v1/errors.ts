export const ErrorDetailSchema = z.object({ field: z.string(), message: z.string() });

/** `details` is allowed only with `validation_failed`. */
export const ApiErrorSchema = z.object({
  error: z
    .object({
      code: ErrorCodeSchema,
      message: z.string(),
      requestId: z.string(),
      details: z.array(ErrorDetailSchema).optional(),
    })
    .refine((e) => e.details === undefined || e.code === 'validation_failed', {
      message: 'details are only allowed with validation_failed',
    }),
});
export type ApiError = z.infer<typeof ApiErrorSchema>;

