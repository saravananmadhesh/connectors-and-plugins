/** Errors reported inside an MCP tool-error result rather than as an HTTP status. */
export const McpToolErrorCodeSchema = z.enum([
  'needs_connect',
  'needs_reauth',
  'component_inactive',
  'tool_not_found',
  'result_too_large',
]);
export type McpToolErrorCode = z.infer<typeof McpToolErrorCodeSchema>;

export const McpToolErrorResultSchema = z.object({
  isError: z.literal(true),
  content: z.array(z.object({ type: z.literal('text'), text: z.string() })),
  structuredContent: z.object({
    code: McpToolErrorCodeSchema,
    connectUrl: z.string().optional(),
  }),
});
export type McpToolErrorResult = z.infer<typeof McpToolErrorResultSchema>;
